#!/usr/bin/env bash
# Builds and self-tests the OpenSSL FIPS provider module tracked by
# CMVP certificate #4985 (FIPS 140-3, "OpenSSL FIPS Provider", Active,
# sunset 2030-03-10 -- verify this is still current before relying on it:
# https://csrc.nist.gov/projects/cryptographic-module-validation-program/certificate/4985),
# then writes an openssl.cnf-style config that activates it in an
# approved-mode-compliant configuration.
#
# Do NOT point OPENSSL_VERSION below at "whatever the latest release is" --
# only the exact version named in a certificate's Security Policy is
# validated. As of this writing:
#   - Certs #4282 / #4811 (FIPS 140-2, OpenSSL 3.0.8/3.0.9) sunset
#     2026-09-21 -- do not build new work against these.
#   - Cert #4985 (FIPS 140-3, OpenSSL 3.1.2) is Active until 2030-03-10.
#     Its Security Policy: https://www.openssl-library.org/source/fips-doc/openssl-3.1.2-security-policy-2023-12-29.pdf
# Re-check https://www.openssl.org/source/ and the CMVP list before
# shipping -- certificate status can change.
set -euo pipefail

OPENSSL_VERSION="3.1.2"
# Published at https://www.openssl.org/source/openssl-3.1.2.tar.gz.sha256
# and cross-checked against https://www.openssl.org/source/ -- verify this
# still matches if you bump OPENSSL_VERSION.
EXPECTED_SHA256="a0ce69b8b97ea6a35b96875235aa453b966ba3cba8af2de23657d8b6767d6539"

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
WORK_DIR="${PROJECT_ROOT}/.fips-build"
MODULE_DIR="${PROJECT_ROOT}/fips-module"
SRC_DIR="${WORK_DIR}/openssl-${OPENSSL_VERSION}"
TARBALL="${WORK_DIR}/openssl-${OPENSSL_VERSION}.tar.gz"
# The exact source distribution named in the Security Policy's Crypto
# Officer Guidance (Section 11.i.a) -- not a GitHub release tarball, which
# is a different artifact even when the version number matches.
URL="https://www.openssl.org/source/openssl-${OPENSSL_VERSION}.tar.gz"

mkdir -p "${WORK_DIR}" "${MODULE_DIR}"

if [[ ! -f "${TARBALL}" ]]; then
  echo "Downloading OpenSSL ${OPENSSL_VERSION} source ..."
  curl -sSL -o "${TARBALL}" "${URL}"
fi

actual_sha256="$(sha256sum "${TARBALL}" | cut -d' ' -f1)"
if [[ "${actual_sha256}" != "${EXPECTED_SHA256}" ]]; then
  echo "FATAL: ${TARBALL} sha256 mismatch." >&2
  echo "  expected: ${EXPECTED_SHA256}" >&2
  echo "  actual:   ${actual_sha256}" >&2
  echo "  Do not proceed -- this is not the validated source distribution." >&2
  exit 1
fi
echo "Source checksum verified against the Security Policy's published value."

if [[ ! -d "${SRC_DIR}" ]]; then
  tar xzf "${TARBALL}" -C "${WORK_DIR}"
fi

if [[ ! -f "${SRC_DIR}/providers/fips.so" ]]; then
  echo "Configuring and building the fips provider (builds all of OpenSSL, a few minutes) ..."
  ( cd "${SRC_DIR}" && ./Configure enable-fips && make -j"$(nproc)" )
fi

cp "${SRC_DIR}/providers/fips.so" "${MODULE_DIR}/fips.so"

echo "Running fipsinstall -pedantic (executes FIPS self-tests, sets the"
echo "Approved-mode-required options from Security Policy section 2.ii) ..."
# -pedantic sets exactly the flags Section 2.ii "Conditions for using the
# Module in the Approved mode" requires: security-checks=1,
# conditional-errors=1, drbg-no-trunc-md=1 (-no_drbg_truncated_digests),
# tls1-prf-ems-check=1 (-ems_check), plus a bundle of related digest/key
# checks. Do not omit it and do not hand-edit these values afterward.
LD_LIBRARY_PATH="${SRC_DIR}" "${SRC_DIR}/apps/openssl" fipsinstall -pedantic \
  -module "${MODULE_DIR}/fips.so" \
  -out "${MODULE_DIR}/fipsmodule.cnf" \
  -provider_name fips \
  -section_name fips_sect

cat > "${PROJECT_ROOT}/openssl-fips.cnf" <<EOF
# Generated by scripts/setup_fips_module.sh -- do not hand-edit paths or
# values here, rerun the script instead. Activate it via:
#   OPENSSL_MODULES=${MODULE_DIR} OPENSSL_CONF=${PROJECT_ROOT}/openssl-fips.cnf ./build/fips_file_crypt
# (OPENSSL_MODULES tells the provider loader where to find fips.so, since it
# isn't installed into the system's default modules directory.)

openssl_conf = openssl_init

# Comment out the next line to ignore config errors instead of aborting.
config_diagnostics = 1

.include ${MODULE_DIR}/fipsmodule.cnf

[openssl_init]
providers = provider_sect
alg_section = evp_properties

[evp_properties]
# Required by Security Policy guidance: makes
# EVP_default_properties_is_fips_enabled() report true and suppresses
# non-approved algorithms the FIPS module itself exposes.
default_properties = "fips=yes"

[provider_sect]
fips = fips_sect
base = base_sect

[base_sect]
activate = 1
EOF

echo
echo "Done. Module:    ${MODULE_DIR}/fips.so (OpenSSL FIPS Provider ${OPENSSL_VERSION}, CMVP cert #4985)"
echo "      Config:    ${PROJECT_ROOT}/openssl-fips.cnf"
echo
echo "Run the demo in FIPS mode with:"
echo "  OPENSSL_MODULES=${MODULE_DIR} OPENSSL_CONF=${PROJECT_ROOT}/openssl-fips.cnf ./build/fips_file_crypt"
echo
echo "Reminder: only AES-256-GCM (and the other Table 3 / Table 4 algorithms in"
echo "the Security Policy) run in Approved mode. Do not use 3DES, Ed25519,"
echo "Ed448, X25519 or X448 for anything that needs to be FIPS-approved --"
echo "Security Policy Table 5 lists them as explicitly disallowed in Approved mode."
